#!/usr/bin/env python3
"""Regenerates src/weights.rs (the gain-match weights) and src/butterworth.rs (the Butterworth Qs).

Run from the repository root:

    python crates/parametric-eq/tools/gen_tables.py

The output is byte-identical to the committed files; `git diff --exit-code crates/parametric-eq/src`
after a run proves it.

Weights (ADR 0054 decision 7): `w_i = |K(f_i)|^2` at the 1,914 frequencies `f_i = 20 * 2^(i/192)` Hz,
i = 0 ... 1913, where `K` is the BS.1770 K-weighting as the standard publishes it for 48 kHz: its
two biquads' coefficients, evaluated as digital filters at 48 kHz. Python's float repr is the
shortest string that round-trips, so each Rust literal parses to the same f64 bits.

Butterworth Qs (decision 2.1): the N-pole Butterworth low pass has its poles on the unit circle at
angles `phi = pi (N - 2i + 1) / (2N)` from the negative real axis, i = 1 ... floor(N/2) (a conjugate pair
each), plus one real pole when N is odd. A pair's damping is `cos(phi)`, so its section Q is
`1 / (2 cos(phi))`. For even N the angles are pi (2j - 1) / (2N); for odd N they are pi m / N, m = 1 ...
(N - 1)/2 (N = 3: one pair at 60 degrees, Q = 1, and the first-order section). The record's
`1 / (2 cos(pi (2i - 1) / (2N)))` holds for even N only. Evaluated in 50-digit decimal arithmetic, so
each literal is the correctly rounded double; listed ascending, for the eight slopes N = 1, 2, 3, 4, 6, 8,
12, 16 (6 to 96 dB per octave).
"""
import cmath
import math
from decimal import Decimal, getcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "crates/parametric-eq/src"
POINTS = 1914
PER_LINE = 4

# ITU-R BS.1770 K-weighting at 48 kHz: the pre-filter (high shelf) and the RLB high pass.
STAGE1 = ((1.53512485958697, -2.69169618940638, 1.19839281085285), (1.0, -1.69065929318241, 0.73248077421585))
STAGE2 = ((1.0, -2.0, 1.0), (1.0, -1.99004745483398, 0.99007225036621))
FS = 48000.0


def biquad_power(stage, f):
    (b0, b1, b2), (a0, a1, a2) = stage
    z1 = cmath.exp(-1j * 2.0 * math.pi * f / FS)
    z2 = z1 * z1
    h = (b0 + b1 * z1 + b2 * z2) / (a0 + a1 * z1 + a2 * z2)
    return abs(h) ** 2


def weights():
    out = []
    for i in range(POINTS):
        f = 20.0 * 2.0 ** (i / 192.0)
        out.append(biquad_power(STAGE1, f) * biquad_power(STAGE2, f))
    return out


def write_weights():
    w = weights()
    lines = [
        "//! The gain-match weights (ADR 0054 decision 7): `|K(f_i)|^2` at `f_i = 20 * 2^(i/192)` Hz, i = 0 ... 1913,",
        "//! `K` the BS.1770 K-weighting as the standard publishes it for 48 kHz (its two biquads). A pink",
        "//! spectrum has constant power per log-spaced point, so these are the whole weight. Generated by",
        "//! `tools/gen_tables.py`, not edited; literals, so they depend on no sample rate and no platform function.",
        "",
        "/// Points on the 1/192-octave gain-match grid, 20 Hz to 19.97 kHz.",
        f"pub(crate) const POINTS: usize = {POINTS};",
        "",
        "/// `|K(f_i)|^2` for each grid point.",
        "#[rustfmt::skip]",
        f"pub(crate) static WEIGHTS: [f64; POINTS] = [",
    ]
    for k in range(0, POINTS, PER_LINE):
        lines.append("    " + " ".join(f"{repr(v)}," for v in w[k:k + PER_LINE]))
    lines.append("];")
    (OUT / "weights.rs").write_text("\n".join(lines) + "\n", newline="\n")


# pi to 60 digits, for the decimal cosine.
PI = Decimal("3.141592653589793238462643383279502884197169399375105820974944")


def dcos(x):
    """cos(x) by its Taylor series in 50-digit decimal arithmetic (|x| < pi/2 here)."""
    getcontext().prec = 50
    term, total, k = Decimal(1), Decimal(1), 0
    while True:
        k += 2
        term = -term * x * x / (k * (k - 1))
        if abs(term) < Decimal(10) ** -55:
            return total
        total += term


def butterworth_qs(n):
    """The ascending section Qs of the n-pole Butterworth, from its pole angles."""
    getcontext().prec = 50
    qs = []
    for i in range(1, n // 2 + 1):
        phi = PI * (n - 2 * i + 1) / (2 * n)
        qs.append(float(1 / (2 * dcos(phi))))
    # Cross-check against the poles themselves in double precision.
    poles = [cmath.exp(1j * math.pi * (2 * k + n - 1) / (2 * n)) for k in range(1, n + 1)]
    check = sorted(1 / (2 * (-p.real / abs(p))) for p in poles if p.imag > 1e-12)
    assert all(abs(a / b - 1) < 1e-12 for a, b in zip(sorted(qs), check)) and len(qs) == len(check)
    return sorted(qs)


def write_butterworth():
    slopes = [1, 2, 3, 4, 6, 8, 12, 16]
    lines = [
        "//! The Butterworth section Qs of the cuts (ADR 0054 decision 2.1): the N-pole Butterworth's pole pairs",
        "//! sit at `phi = pi (N - 2i + 1) / (2N)` from the negative real axis, i = 1 ... floor(N/2), so each",
        "//! section's Q is `1 / (2 cos(phi))`; odd N adds the first-order section (N = 3: one pair, Q = 1). For",
        "//! even N this is `1 / (2 cos(pi (2i - 1) / (2N)))`; for odd N it is not. Ascending, for N = slope / 6.",
        "//! Generated by `tools/gen_tables.py` (correctly rounded), not edited; literals, so no platform",
        "//! function runs.",
        "",
        "/// The second-order Qs of each slope, in slope order (6, 12, 18, 24, 36, 48, 72, 96 dB per octave).",
        "// The correctly rounded 1/sqrt(2) appears as a literal like the other Qs.",
        "#[allow(clippy::approx_constant)]",
        "#[rustfmt::skip]",
        "pub(crate) static QS: [&[f64]; 8] = [",
    ]
    for n in slopes:
        qs = butterworth_qs(n)
        body = ", ".join(repr(q) for q in qs)
        lines.append(f"    &[{body}],")
    lines.append("];")
    (OUT / "butterworth.rs").write_text("\n".join(lines) + "\n", newline="\n")


if __name__ == "__main__":
    write_weights()
    write_butterworth()
