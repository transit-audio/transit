#!/usr/bin/env python3
"""Regenerates src/resources.rs from the vendored firmware sources.

Run from the repository root:

    python crates/modulator/tools/gen_resources.py

It copies, verbatim, the literals of the tables the meta-modulator's processing path reads from
crates/macro-osc-oracle/vendor/warps/resources.cc (the filter bank's 20 band rows, lut_sin,
lut_xfade_in, lut_xfade_out, lut_bipolar_fold, lut_midi_to_f_high, lut_midi_to_f_low) and the six
converter kernels of crates/macro-osc-oracle/vendor/warps/dsp/sample_rate_conversion_filters.h.
Every literal there is a double literal the C++ initializer narrows to float, so each table is
written as `f64` literals and narrowed by a const fn, as the C++ does. The output is
byte-identical to the committed file; `git diff --exit-code crates/modulator/src` after a run
proves it. To move to a new firmware pin: re-vendor, update the pin in HEADER, run this, then the
nulls.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
VENDOR = ROOT / "crates/macro-osc-oracle/vendor/warps"
OUT = ROOT / "crates/modulator/src/resources.rs"
PER_LINE = 8

HEADER = """//! The meta-modulator's lookup tables and converter kernels, generated from `warps/resources.cc`
//! and `warps/dsp/sample_rate_conversion_filters.h` (eurorack `08460a69`, Émilie Gillet, MIT; see
//! LICENSE-THIRD-PARTY). The literals are the C++'s, verbatim: double literals the C++ initializers
//! narrow to `float`, so they are kept as `f64` and narrowed the same way. Generated by
//! `tools/gen_resources.py`, not edited.

#![forbid(unsafe_code)]
// Table data, verbatim.
#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]

/// Narrows double literals to `float`, as a C++ `const float` initializer does.
const fn narrow<const N: usize>(x: &[f64; N]) -> [f32; N] {
    let mut out = [0.0_f32; N];
    let mut i = 0;
    while i < N {
        #[allow(clippy::cast_possible_truncation)]
        let v = x[i] as f32;
        out[i] = v;
        i += 1;
    }
    out
}
"""

NUMBER = re.compile(r"-?\d+\.\d+e[+-]\d+")


def array(text, name):
    m = re.search(r"const float " + re.escape(name) + r"\[\] = \{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    return NUMBER.findall(m.group(1))


def kernel(text, direction, ratio, length):
    m = re.search(
        r"struct SRC_FIR<SRC_" + direction + r", " + str(ratio) + r", " + str(length) + r"> \{.*?const float h\[\] = \{(.*?)\};",
        text,
        re.S,
    )
    if not m:
        raise SystemExit(f"kernel {direction} {ratio} {length} not found")
    return NUMBER.findall(m.group(1))


def table(doc, name, values, public_name, out):
    n = len(values)
    out.append(f"\n/// {doc}\n")
    out.append("#[rustfmt::skip]\n")
    out.append(f"const {name}_LITERALS: [f64; {n}] = [\n")
    for i in range(0, n, PER_LINE):
        out.append("    " + " ".join(v + "," for v in values[i : i + PER_LINE]) + "\n")
    out.append("];\n")
    out.append(f"pub(crate) static {public_name}: [f32; {n}] = narrow(&{name}_LITERALS);\n")


def main():
    resources = (VENDOR / "resources.cc").read_text(encoding="utf-8")
    filters = (VENDOR / "dsp/sample_rate_conversion_filters.h").read_text(encoding="utf-8")
    out = [HEADER]
    names = re.search(r"const float\* filter_bank_table\[\] = \{(.*?)\};", resources, re.S).group(1).split(",")
    names = [n.strip() for n in names if n.strip()]
    rows = []
    for n in names:
        rows.extend(array(resources, n))
    if len(names) != 20 or len(rows) != 140:
        raise SystemExit("unexpected filter bank table")
    table(
        "`filter_bank_table`: per band, from the lowest, the decimation factor, the group delay (in "
        "decimated samples), the post gain and the two crossover filters' `f` and `fq` (`fb_*`, 7 "
        "values each, rows concatenated).",
        "FILTER_BANK",
        rows,
        "FILTER_BANK",
        out,
    )
    table("`lut_sin`: a sine period over 1024 steps plus a quarter.", "LUT_SIN", array(resources, "lut_sin"), "LUT_SIN", out)
    table("`lut_xfade_in`: the crossfade algorithm's fade-in curve.", "LUT_XFADE_IN", array(resources, "lut_xfade_in"), "LUT_XFADE_IN", out)
    table("`lut_xfade_out`: its fade-out curve.", "LUT_XFADE_OUT", array(resources, "lut_xfade_out"), "LUT_XFADE_OUT", out)
    table(
        "`lut_bipolar_fold`: the fold algorithm's wavefolder, read from its middle.",
        "LUT_BIPOLAR_FOLD",
        array(resources, "lut_bipolar_fold"),
        "LUT_BIPOLAR_FOLD",
        out,
    )
    table(
        "`lut_midi_to_f_high`: the phase increment per 256 steps of pitch (at 96 kHz).",
        "LUT_MIDI_TO_F_HIGH",
        array(resources, "lut_midi_to_f_high"),
        "LUT_MIDI_TO_F_HIGH",
        out,
    )
    table(
        "`lut_midi_to_f_low`: the fine factor per 1/256 of a step.",
        "LUT_MIDI_TO_F_LOW",
        array(resources, "lut_midi_to_f_low"),
        "LUT_MIDI_TO_F_LOW",
        out,
    )
    for direction, ratio, length, what in [
        ("UP", 6, 48, "the 6x up converter (half of a 48-tap kernel)"),
        ("DOWN", 6, 48, "the 6x down converter"),
        ("UP", 4, 48, "the vocoder's 4x up converter"),
        ("DOWN", 4, 48, "the vocoder's 4x down converter"),
        ("UP", 3, 36, "the vocoder's 3x up converter (half of a 36-tap kernel)"),
        ("DOWN", 3, 36, "the vocoder's 3x down converter"),
    ]:
        name = f"SRC_{direction}_{ratio}_{length}"
        table(f"`SRC_FIR<SRC_{direction}, {ratio}, {length}>`: {what}.", name, kernel(filters, direction, ratio, length), name, out)
    OUT.write_text("".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
