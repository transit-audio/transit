#!/usr/bin/env python3
"""Regenerates src/resources/ from the vendored firmware sources.

Run from the repository root:

    python crates/random-sequencer/tools/gen_resources.py

It copies, verbatim, the literals of the tables the random sequencer reads from
crates/macro-osc-oracle/vendor/marbles/resources.cc: lut_raised_cosine (the lag processor's
interpolation shape), lut_logit (the Markov model) and the 45 inverse-cdf tables of the beta
distributions (dist_icdf_<bias>_<spread>, 387 values each), and the order of distributions_table
(60 entries: each bias row padded with its last spread, and the last row repeated). lut_sine feeds
only the firmware's output test and is left out. Every literal there is a double literal the C++
initializer narrows to float, so each table is written as `f64` literals and narrowed by a const
fn, as the C++ does. The output is byte-identical to the committed files; `git diff --exit-code
crates/random-sequencer/src` after a run proves it. To move to a new firmware pin: re-vendor,
update the pin in the headers, run this, then the nulls.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "crates/macro-osc-oracle/vendor/marbles/resources.cc"
OUT = ROOT / "crates/random-sequencer/src/resources"
PER_LINE = 8
PIN = "eurorack `08460a69`, Émilie Gillet, MIT; see LICENSE-THIRD-PARTY"

NUMBER = re.compile(r"-?\d+\.\d+e[+-]\d+")


def array(text, name):
    m = re.search(r"const float " + re.escape(name) + r"\[\] = \{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    return NUMBER.findall(m.group(1))


def table(out, doc, name, values, narrow="super::narrow"):
    n = len(values)
    out.append(f"\n/// {doc}\n")
    out.append("#[rustfmt::skip]\n")
    out.append(f"static {name}_LITERALS: [f64; {n}] = [\n")
    for i in range(0, n, PER_LINE):
        out.append("    " + " ".join(v + "," for v in values[i : i + PER_LINE]) + "\n")
    out.append("];\n")
    out.append(f"pub(crate) static {name}: [f32; {n}] = {narrow}(&{name}_LITERALS);\n")


def main():
    text = SOURCE.read_text(encoding="utf-8")
    order = re.search(r"const float\* distributions_table\[\] = \{(.*?)\};", text, re.S).group(1)
    order = re.findall(r"dist_icdf_(\d)_(\d)", order)
    if len(order) != 60:
        raise SystemExit(f"distributions_table has {len(order)} entries, expected 60")

    mod = []
    mod.append(f"""//! The random sequencer's lookup tables, generated from `marbles/resources.cc`
//! ({PIN}).
//! The literals are the C++'s, verbatim: double literals the C++ initializers narrow to `float`,
//! so they are kept as `f64` and narrowed the same way. Generated by `tools/gen_resources.py`, not
//! edited.

#![forbid(unsafe_code)]
// Table data, verbatim.
#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]

mod icdf_0;
mod icdf_1;
mod icdf_2;
mod icdf_3;
mod icdf_4;

/// Narrows double literals to `float`, as a C++ `const float` initializer does.
const fn narrow<const N: usize>(x: &[f64; N]) -> [f32; N] {{
    let mut out = [0.0_f32; N];
    let mut i = 0;
    while i < N {{
        #[allow(clippy::cast_possible_truncation)]
        let v = x[i] as f32;
        out[i] = v;
        i += 1;
    }}
    out
}}

/// Values per inverse-cdf table: three sub-tables of 129 (the body, then the lowest and highest
/// 5 % at higher resolution).
pub(crate) const ICDF_SIZE: usize = 387;
""")
    table(mod, "The lag processor's interpolation shape, `lut_raised_cosine`.", "LUT_RAISED_COSINE", array(text, "lut_raised_cosine"), "narrow")
    table(mod, "The Markov model's logistic curve, `lut_logit`.", "LUT_LOGIT", array(text, "lut_logit"), "narrow")
    mod.append("\n/// `distributions_table`: the inverse-cdf table per cell (bias row of 10, spread column), in the\n")
    mod.append("/// C++'s order, each row padded with its last spread and the last row repeated.\n")
    mod.append("#[rustfmt::skip]\n")
    mod.append("pub(crate) static DISTRIBUTIONS: [&[f32; ICDF_SIZE]; 60] = [\n")
    for i in range(0, 60, 5):
        mod.append("    " + " ".join(f"&icdf_{b}::DIST_ICDF_{b}_{s}," for b, s in order[i : i + 5]) + "\n")
    mod.append("];\n")
    mod.append("\n/// `dist_icdf_4_3`: the jitter's beta(3, 3) with a fatter tail.\n")
    mod.append("pub(crate) static DIST_ICDF_4_3: &[f32; ICDF_SIZE] = &icdf_4::DIST_ICDF_4_3;\n")
    (OUT / "mod.rs").write_text("".join(mod), encoding="utf-8", newline="\n")

    for b in range(5):
        out = []
        out.append(f"""//! The inverse-cdf tables of bias row {b}, generated from `marbles/resources.cc`
//! ({PIN}).
//! Generated by `tools/gen_resources.py`, not edited.

#![forbid(unsafe_code)]
#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]
""")
        for s in range(9):
            values = array(text, f"dist_icdf_{b}_{s}")
            if len(values) != 387:
                raise SystemExit(f"dist_icdf_{b}_{s} has {len(values)} values")
            table(out, f"`dist_icdf_{b}_{s}`.", f"DIST_ICDF_{b}_{s}", values)
        (OUT / f"icdf_{b}.rs").write_text("".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
