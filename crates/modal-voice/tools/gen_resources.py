#!/usr/bin/env python3
"""Regenerates the modal voice's tables from the vendored firmware resources file.

Run from the repository root:

    python crates/modal-voice/tools/gen_resources.py

It parses crates/macro-osc-oracle/vendor/elements/resources.cc (eurorack 08460a69, Emilie Gillet,
MIT) and writes, into crates/modal-voice/src/:

- resources.rs: every float table the port reads, its literals copied verbatim as f64 and
  narrowed to f32 by a const fn (the C++ `const float` initializers narrow the same double
  literals), except the sine; and the sample boundaries;
- resources_sine.rs: `lut_sine` (4097 entries), the same way;
- samples_1.rs to samples_5.rs: `smp_sample_data` (128013 int16, the strike's nine samples) in
  five chunks, 20 values to a line, joined in src/samples.rs;
- noise_1.rs and noise_2.rs: `smp_noise_sample` (40963 int16, the blow's noise) in two chunks.

The output is byte-identical to the committed files; `git diff --exit-code crates/modal-voice/src`
after a run proves it. To move to a new firmware pin: re-vendor, update PIN, run this, then the
null tests.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "crates/macro-osc-oracle/vendor/elements/resources.cc"
OUT = ROOT / "crates/modal-voice/src"
PIN = "eurorack `08460a69`"
CREDIT = f"({PIN}, Émilie Gillet, MIT; see LICENSE-THIRD-PARTY)"

FLOAT_TABLES = [
    ("lut_approx_svf_gain", 257, "the strike pulse's amplitude per cutoff (`GetPulseAmplitude`)"),
    ("lut_approx_svf_g", 257, "the exciter filter's `g` per cutoff"),
    ("lut_approx_svf_r", 257, "the exciter filter's `r` per resonance"),
    ("lut_approx_svf_h", 257, "the exciter filter's `h` per cutoff"),
    ("lut_4_decades", 257, "10^(4x): the modal resonator's Q"),
    ("lut_accent_gain_coarse", 257, "the strength's coarse gain (3 dB/V)"),
    ("lut_accent_gain_fine", 257, "the strength's fine gain"),
    ("lut_stiffness", 257, "the modal resonator's stiffness per geometry"),
    ("lut_env_increments", 258, "the envelope's phase increment per time"),
    ("lut_env_linear", 258, "the envelope's linear segment shape"),
    ("lut_env_expo", 258, "the envelope's exponential segment shape"),
    ("lut_env_quartic", 258, "the envelope's quartic segment shape"),
    ("lut_midi_to_f_high", 256, "frequency per semitone (coarse), MIDI -48 up"),
    ("lut_midi_to_increment_high", 256, "phase increment per semitone (coarse), for the FM pair"),
    ("lut_midi_to_f_low", 256, "the fractional semitone's ratio (fine)"),
    ("lut_fm_frequency_quantizer", 129, "the FM pair's ratio per meta control"),
    ("lut_detune_quantizer", 65, "the FM pair's detune per bow level"),
    ("lut_svf_shift", 257, "the string's damping filter delay compensation"),
]

HEADER = """//! The modal voice's float lookup tables, generated from `elements/resources.cc` {credit}. The
//! literals are the C++'s, verbatim: double literals a `const float` initializer narrows to
//! `float`, so they are kept as `f64` and narrowed the same way. Generated by
//! `tools/gen_resources.py`, not edited.

#![forbid(unsafe_code)]
// Table data: some values happen to be close to named constants.
#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]

/// Narrows double literals to `float`, as a C++ `const float` initializer does.
pub(crate) const fn narrow<const N: usize>(x: &[f64; N]) -> [f32; N] {{
    let mut out = [0.0_f32; N];
    let mut i = 0;
    while i < N {{
        #[allow(clippy::cast_possible_truncation)]
        let v = x[i] as f32;
        out[i] = v;
        i += 1;
    }}
    out
}}
"""

SINE_HEADER = """//! `lut_sine` (a sine period over 4096 steps plus the first entry again), generated from
//! `elements/resources.cc` {credit}, its double literals narrowed to `float` as the C++ initializer
//! does. Generated by `tools/gen_resources.py`, not edited.

#![forbid(unsafe_code)]
#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal, clippy::large_const_arrays)]

use crate::resources::narrow;
"""

CHUNK_HEADER = """//! `{name}`, entries {start} to {end}: generated from `elements/resources.cc`
//! {credit}, split for the line budget and joined in [`crate::samples`]. Generated by
//! `tools/gen_resources.py`, not edited.

#![forbid(unsafe_code)]

/// {what}
#[rustfmt::skip]
pub(crate) static {ident}: [i16; {count}] = [
"""


def body(text, name):
    start = text.index(name + "[] = {")
    b = text[text.index("{", start) + 1 : text.index("};", start)]
    return re.sub(r"//[^\n]*", "", b)


def floats(text, name):
    return re.findall(r"-?\d+\.\d+e[-+]\d+", body(text, name))


def ints(text, name):
    return [int(t) for t in re.findall(r"-?\d+", body(text, name))]


def lines(values, per_line):
    return "\n".join("    " + ", ".join(values[i : i + per_line]) + "," for i in range(0, len(values), per_line))


def float_table(name, literals, what):
    ident = name.upper()
    n = len(literals)
    return (
        f"\n/// `{name}`'s literals: {what}.\n#[rustfmt::skip]\nconst {ident}_LITERALS: [f64; {n}] = [\n"
        + lines(literals, 8)
        + f"\n];\n/// `{name}`.\npub(crate) static {ident}: [f32; {n}] = narrow(&{ident}_LITERALS);\n"
    )


def write(path, text):
    path.write_text(text, encoding="utf-8", newline="\n")


def chunks(name, prefix, values, sizes, what):
    start = 0
    for i, size in enumerate(sizes, 1):
        part = [str(v) for v in values[start : start + size]]
        ident = f"{prefix.upper()}_{i}"
        header = CHUNK_HEADER.format(name=name, start=start, end=start + size - 1, credit=CREDIT, what=what, ident=ident, count=size)
        write(OUT / f"{prefix}_{i}.rs", header + lines(part, 20) + "\n];\n")
        start += size
    assert start == len(values), (name, start, len(values))


def main():
    text = SOURCE.read_text(encoding="utf-8")
    out = HEADER.format(credit=CREDIT)
    for name, size, what in FLOAT_TABLES:
        literals = floats(text, name)
        assert len(literals) == size, (name, len(literals))
        out += float_table(name, literals, what)
    boundaries = ints(text, "smp_boundaries")
    assert boundaries == [0, 17099, 20852, 30369, 63050, 85807, 95952, 106297, 117606, 128013], boundaries
    out += (
        "\n/// `smp_boundaries`: where each of the nine strike samples starts in `smp_sample_data`, and its end.\n"
        f"pub(crate) static SMP_BOUNDARIES: [usize; 10] = [{', '.join(str(b) for b in boundaries)}];\n"
    )
    write(OUT / "resources.rs", out)

    sine = floats(text, "lut_sine")
    assert len(sine) == 4097, len(sine)
    write(OUT / "resources_sine.rs", SINE_HEADER.format(credit=CREDIT) + float_table("lut_sine", sine, "a sine period over 4096 steps"))

    samples = ints(text, "smp_sample_data")
    assert len(samples) == 128013, len(samples)
    chunks("smp_sample_data", "samples", samples, [25600, 25600, 25600, 25600, 25613], "A chunk of the strike's nine samples (16-bit).")
    noise = ints(text, "smp_noise_sample")
    assert len(noise) == 40963, len(noise)
    chunks("smp_noise_sample", "noise", noise, [20480, 20483], "A chunk of the blow's noise sample (16-bit).")
    print(f"{len(FLOAT_TABLES)} float tables, lut_sine, {len(samples)} sample and {len(noise)} noise values")


if __name__ == "__main__":
    sys.exit(main())
