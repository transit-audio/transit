"""Arbitrary-precision DFT reference for transit-math's FFT (ADR 0055 slice 2b).

Pure Python `decimal` and `fractions`, no third-party package. From this folder, run:

    python -I fft_reference.py <outdir>

It regenerates fft_reference.txt byte for byte (point <outdir> at this folder to overwrite it, or
elsewhere and diff). The inputs come from the same xorshift32 generator and exact scaling as the
crate's tests (`tests/fft_support/mod.rs`): a 24-bit integer over 2^23, exact in f32 and f64. Each
bin is the exact DFT sum over 60-digit twiddles (pi by Machin's formula, sine and cosine by their
series), written with 30 significant digits, so the file is the true DFT to far below an f64 ulp.

Cases (kind, size, seed): the forward transform X[k] = sum_j x[j] e^(-2 pi i j k / n).
  real 256 0x2b2b0100     bins 0..=128 of 256 real samples
  complex 256 0x2b2b0200  bins 0..256 of 256 complex samples (re, im drawn in that order)
  real 1024 0x2b2b0400    bins 0..=512 of 1024 real samples
"""

import os
import sys
from decimal import Decimal as D, getcontext

getcontext().prec = 60

CASES = [("real", 256, 0x2B2B0100), ("complex", 256, 0x2B2B0200), ("real", 1024, 0x2B2B0400)]


def xorshift32(state):
    while True:
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        yield state


def samples(seed, count):
    g = xorshift32(seed)
    out = []
    for _ in range(count):
        i = (next(g) >> 8) - (1 << 23)
        out.append(D(i) / D(1 << 23))  # exact: 23 binary places need 23 decimal places
    return out


def atan_inv(x):
    """atan(1/x) by its series."""
    x = D(x)
    x2 = x * x
    term = 1 / x
    total = term
    k = 1
    eps = D(10) ** -(getcontext().prec + 2)
    while abs(term) > eps:
        term = -term / x2
        total += term / (2 * k + 1)
        k += 1
    return total


PI = 16 * atan_inv(5) - 4 * atan_inv(239)


def cos_sin(t):
    """cos(t), sin(t) for |t| <= 2 pi by their series."""
    eps = D(10) ** -(getcontext().prec + 2)
    c = D(1)
    s = t
    term_c = D(1)
    term_s = t
    t2 = t * t
    k = 1
    while abs(term_c) > eps or abs(term_s) > eps:
        term_c = -term_c * t2 / ((2 * k - 1) * (2 * k))
        term_s = -term_s * t2 / ((2 * k) * (2 * k + 1))
        c += term_c
        s += term_s
        k += 1
    return c, s


def dft(values, n, bins):
    """values: list of (re, im) Decimals; returns bins 0..bins-1 of the forward DFT."""
    tw = [cos_sin(2 * PI * m / n) for m in range(n)]
    out = []
    for k in range(bins):
        re = D(0)
        im = D(0)
        for j, (a, b) in enumerate(values):
            c, s = tw[(j * k) % n]
            re += a * c + b * s
            im += b * c - a * s
        out.append((re, im))
    return out


def fmt(d):
    return "0" if d == 0 else format(d, ".29e")


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else "."
    lines = [
        "# Arbitrary-precision forward DFT of the FFT tests' integer-generated inputs (ADR 0055 slice 2b).",
        "# Generated by fft_reference.py beside this file (python -I fft_reference.py <outdir>); do not edit.",
        "# Each case: a 'case <kind> <n> <seed>' line, then 'k re im' per bin, 30 significant digits.",
    ]
    for kind, n, seed in CASES:
        if kind == "real":
            x = [(v, D(0)) for v in samples(seed, n)]
            bins = n // 2 + 1
        else:
            s = samples(seed, 2 * n)
            x = [(s[2 * j], s[2 * j + 1]) for j in range(n)]
            bins = n
        lines.append(f"case {kind} {n} 0x{seed:08x}")
        for k, (re, im) in enumerate(dft(x, n, bins)):
            lines.append(f"{k} {fmt(+re)} {fmt(+im)}")
    path = os.path.join(outdir, "fft_reference.txt")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}: {len(lines)} lines")


if __name__ == "__main__":
    main()
