//! `cargo xtask indexes [--validate | --check | --split-legacy]` (ADR 0050): the known-issues, ADR and escapes
//! indexes are generated from one file per entry, so a contributor never edits a shared table.
//!
//! - `cargo xtask indexes` validates the entries, then rewrites the generated block of each README.
//! - `--validate` only validates the entry files (what a pull request is checked with).
//! - `--check` validates, then fails when a committed block differs from what the entries produce (the gate on
//!   `main` and in the landing chain).
//! - `--split-legacy` is the one-shot converter that made the entry files from the old hand-edited tables.
//!
//! A known-issue entry starts with a hidden comment block, which GitHub does not render: `<!-- transit-index`,
//! one `key: value` per line (the value is everything after the first `: `), then `-->`; the issue text follows
//! as one paragraph that may be wrapped (the table row joins its lines). Its relative links are written from the
//! entry's own folder and rebased to the README's folder when the row is written. An ADR or escape needs no
//! block: the index text comes from its `#` heading and, for an ADR, its `**Status:**` line. A block with a `title`
//! overrides the heading's, and the converter wrote one only where a legacy row differs from what the heading
//! gives; the status is never overridden.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

pub const BEGIN: &str = "<!-- indexes:begin (generated by `cargo xtask indexes`; edit the entry files, not this block) -->";
pub const END: &str = "<!-- indexes:end -->";
const META_OPEN: &str = "<!-- transit-index\n";
const META_CLOSE: &str = "-->";

const KNOWN_README: &str = "docs/known-issues/README.md";
const KNOWN_ENTRIES: &str = "docs/known-issues/entries";
const ADR_DIR: &str = "docs/adr";
const ESCAPES_DIR: &str = "docs/escapes";
const KNOWN_HEADER: [&str; 2] = ["| Id | Issue | Status | Gate or follow-up |", "|---|---|---|---|"];
const ADR_HEADER: [&str; 2] = ["| # | Decision | Status |", "|---|---|---|"];

/// The file stems that existed when the tables were converted: the one-time exception to the id rule and the
/// only entries that may carry `order`.
const LEGACY: &str = include_str!("indexes_legacy.txt");

fn is_legacy(stem: &str) -> bool {
    LEGACY.lines().any(|l| l == stem)
}

/// A parsed entry file: the hidden block's pairs in file order (empty when there is none), and the text under it.
#[derive(Debug, PartialEq)]
pub struct Entry {
    pub fields: Vec<(String, String)>,
    pub body: String,
}

impl Entry {
    pub fn get(&self, key: &str) -> Option<&str> {
        self.fields.iter().find(|(k, _)| k == key).map(|(_, v)| v.as_str())
    }
}

pub fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
}

pub fn parse_entry(name: &str, text: &str) -> Result<Entry, String> {
    let text = normalize(text);
    let Some(rest) = text.strip_prefix(META_OPEN) else {
        return Ok(Entry { fields: Vec::new(), body: text.trim_matches('\n').to_string() });
    };
    let mut fields = Vec::new();
    let mut consumed = 0;
    let mut closed = false;
    for line in rest.split_inclusive('\n') {
        consumed += line.len();
        let line = line.trim_end_matches('\n');
        if line == META_CLOSE {
            closed = true;
            break;
        }
        let (key, value) = line.split_once(": ").ok_or_else(|| format!("{name}: index block line without `: `: {line:?}"))?;
        fields.push((key.to_string(), value.to_string()));
    }
    if !closed {
        return Err(format!("{name}: the `<!-- transit-index` block is not closed by a line `-->`"));
    }
    Ok(Entry { fields, body: rest[consumed..].trim_matches('\n').to_string() })
}

pub fn render_entry(fields: &[(&str, &str)], body: &str) -> String {
    let mut out = String::new();
    if !fields.is_empty() {
        out.push_str(META_OPEN);
        for (k, v) in fields {
            out.push_str(&format!("{k}: {v}\n"));
        }
        out.push_str(META_CLOSE);
        out.push('\n');
    }
    if !body.is_empty() {
        if !fields.is_empty() {
            out.push('\n');
        }
        out.push_str(body);
        out.push('\n');
    }
    out
}

#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
enum Chunk {
    Num(u64),
    Text(String),
}

/// Natural order: digit runs compare as numbers (`issue-99` before `issue-380`), the rest byte for byte.
fn natural_key(s: &str) -> Vec<Chunk> {
    let mut out = Vec::new();
    let mut chars = s.chars().peekable();
    while let Some(&c) = chars.peek() {
        let digit = c.is_ascii_digit();
        let mut run = String::new();
        while let Some(&c) = chars.peek() {
            if c.is_ascii_digit() != digit {
                break;
            }
            run.push(c);
            chars.next();
        }
        out.push(if digit { run.parse().map_or(Chunk::Text(run), Chunk::Num) } else { Chunk::Text(run) });
    }
    out
}

fn md_files(dir: &Path) -> Result<Vec<(String, String)>, String> {
    let mut out = Vec::new();
    let reader = fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for item in reader {
        let path = item.map_err(|e| e.to_string())?.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default().to_string();
        if name.ends_with(".md") && name != "README.md" && path.is_file() {
            let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            out.push((name, text));
        }
    }
    out.sort();
    Ok(out)
}

fn field<'a>(entry: &'a Entry, name: &str, key: &str) -> Result<&'a str, String> {
    entry.get(key).ok_or_else(|| format!("{name}: the index block lacks `{key}`"))
}

/// The id rule for a new entry: `issue-<n>` (then `-b`, `-c` for a second entry on the same issue) when a
/// GitHub issue exists, otherwise a short kebab-case slug.
fn id_rule(stem: &str) -> Result<(), String> {
    let kebab =
        !stem.is_empty() && stem.split('-').all(|part| !part.is_empty() && part.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit()));
    if !kebab {
        return Err(format!("{stem}.md: a new entry is named `issue-<number>` or a lowercase kebab-case slug (digits, a-z and single hyphens)"));
    }
    if stem.starts_with("issue-") && !stem["issue-".len()..].starts_with(|c: char| c.is_ascii_digit()) {
        return Err(format!("{stem}.md: a name that starts `issue-` continues with the issue number, as `issue-380`"));
    }
    Ok(())
}

/// The citation id of an escape: the `E<n>` of a legacy file, the stem of a new one.
fn escape_id(stem: &str) -> String {
    let legacy_prefix: String = stem.chars().take_while(|c| *c != '-').collect();
    if is_legacy(stem) && legacy_prefix.starts_with('E') { legacy_prefix } else { stem.to_string() }
}

// ---- relative links ----

fn is_relative(target: &str) -> bool {
    !(target.is_empty() || target.starts_with('#') || target.starts_with('/') || target.contains(':'))
}

/// Applies `f` to the target of every relative markdown link `](target)` in `text`.
fn map_links(text: &str, f: &dyn Fn(&str) -> String) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(at) = rest.find("](") {
        out.push_str(&rest[..at + 2]);
        rest = &rest[at + 2..];
        match rest.find(')') {
            Some(end) if is_relative(&rest[..end]) => {
                out.push_str(&f(&rest[..end]));
                rest = &rest[end..];
            }
            _ => {}
        }
    }
    out.push_str(rest);
    out
}

/// A link written from `entries/` as the README (one folder up) must write it.
pub fn to_readme_target(target: &str) -> String {
    target.strip_prefix("../").map_or_else(|| format!("entries/{target}"), str::to_string)
}

/// The inverse: a link written from the README as the entry (in `entries/`) must write it.
pub fn to_entry_target(target: &str) -> String {
    target.strip_prefix("entries/").map_or_else(|| format!("../{target}"), str::to_string)
}

/// Every relative link in the entry must resolve from the entry's own folder.
pub fn check_links(root: &Path) -> Result<(), String> {
    let dir = root.join(KNOWN_ENTRIES);
    let mut problems = Vec::new();
    for (name, text) in md_files(&dir)? {
        for part in text.split("](").skip(1) {
            let Some(target) = part.split(')').next() else { continue };
            if !is_relative(target) {
                continue;
            }
            let path = target.split(['#', '?']).next().unwrap_or_default();
            if !path.is_empty() && !dir.join(path).exists() {
                problems.push(format!(
                    "{name}: the link `{target}` does not resolve from {KNOWN_ENTRIES}/ (links are written from the entry's own folder)"
                ));
            }
        }
    }
    if problems.is_empty() { Ok(()) } else { Err(problems.join("\n")) }
}

// ---- the three blocks ----

/// The issue text as one table cell: a wrapped paragraph joined with single spaces.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The known-issues table: legacy rows in their historical `order`, then new entries by natural id.
pub fn known_block(files: &[(String, String)]) -> Result<Vec<String>, String> {
    let mut rows = Vec::new();
    let mut problems = Vec::new();
    for (name, text) in files {
        let id = name.trim_end_matches(".md").to_string();
        let legacy = is_legacy(&id);
        let result = (|| {
            let entry = parse_entry(name, text)?;
            if entry.fields.is_empty() {
                return Err(format!("{name}: no `<!-- transit-index` block with a `status:` line at the top; see CONTRIBUTING.md"));
            }
            let order = match entry.get("order") {
                Some(_) if !legacy => {
                    return Err(format!("{name}: `order` is only for the entries converted from the old table; remove it"));
                }
                Some(o) => o.parse::<u64>().map_err(|_| format!("{name}: `order` is not a number: {o}"))?,
                None => u64::MAX,
            };
            if !legacy {
                id_rule(&id)?;
                if entry.body.contains("\n\n") {
                    return Err(format!(
                        "{name}: the text is one paragraph (it may be wrapped); a blank line starts a second one, which the table row cannot hold"
                    ));
                }
                if entry.fields.iter().map(|(_, v)| v.as_str()).chain([entry.body.as_str()]).any(|v| v.contains('|')) {
                    return Err(format!("{name}: a `|` would split the table row; use other punctuation"));
                }
            }
            let rebase = |s: &str| map_links(s, &to_readme_target);
            let mut row = format!("| {id} | {} | {}", rebase(&one_line(&entry.body)), rebase(field(&entry, name, "status")?));
            if let Some(follow) = entry.get("follow-up") {
                row.push_str(&format!(" | {}", rebase(follow)));
            }
            row.push_str(" |");
            Ok(((order, natural_key(&id)), row))
        })();
        match result {
            Ok(row) => rows.push(row),
            Err(e) => problems.push(e),
        }
    }
    if !problems.is_empty() {
        return Err(problems.join("\n"));
    }
    rows.sort_by(|a, b| a.0.cmp(&b.0));
    let mut out: Vec<String> = KNOWN_HEADER.iter().map(|s| s.to_string()).collect();
    out.extend(rows.into_iter().map(|r| r.1));
    Ok(out)
}

fn heading(body: &str) -> Option<&str> {
    body.lines().find_map(|l| l.strip_prefix("# "))
}

/// Splits on `;` and on a sentence end (`. `) outside parentheses.
fn top_level_clauses(line: &str) -> Vec<&str> {
    let (mut out, mut depth, mut start) = (Vec::new(), 0usize, 0usize);
    let bytes = line.as_bytes();
    for (i, c) in line.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            ';' if depth == 0 => {
                out.push(&line[start..i]);
                start = i + 1;
            }
            '.' if depth == 0 && bytes.get(i + 1) == Some(&b' ') => {
                out.push(&line[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&line[start..]);
    out
}

/// A clause without its parentheticals (a link target `](...)` stays), cut at its first `: `.
fn trim_clause(clause: &str) -> String {
    let mut out = String::new();
    let (mut depth, mut prev) = (0usize, ' ');
    let mut link = 0usize;
    for c in clause.chars() {
        match c {
            '(' if depth == 0 && link == 0 && prev == ']' => {
                link = 1;
                out.push(c);
            }
            '(' if link > 0 => {
                link += 1;
                out.push(c);
            }
            ')' if link > 0 => {
                link -= 1;
                out.push(c);
            }
            '(' => depth += 1,
            ')' if depth > 0 => depth -= 1,
            _ if depth > 0 => {}
            _ => out.push(c),
        }
        prev = c;
    }
    let out = out.split_whitespace().collect::<Vec<_>>().join(" ");
    let end = out.find(": ").unwrap_or(out.len());
    out[..end].trim().trim_end_matches(['.', ':']).to_string()
}

/// Whether a clause marks an amendment or a supersession (a whole word, any case).
fn marks_amendment(clause: &str) -> bool {
    clause.split(|c: char| !c.is_alphanumeric()).any(|w| matches!(w.to_lowercase().as_str(), "amended" | "amendment" | "amendments" | "superseded"))
}

/// The short index status derived from a status line: its first clause, plus every later clause (split at `;` or a
/// sentence end) that marks an amendment or a supersession, each without its parentheticals and cut at its first `: `.
pub fn short_status(line: &str) -> String {
    let clauses = top_level_clauses(line);
    let mut kept = vec![trim_clause(clauses[0])];
    kept.extend(clauses[1..].iter().filter(|c| marks_amendment(c)).map(|c| trim_clause(c)));
    kept.retain(|k| !k.is_empty());
    kept.join("; ")
}

/// The (title, status) the index shows for an ADR: the title from the block's override, else the heading; the
/// status always from the record's own `**Status:**` line, so a status change is made in one place.
pub fn adr_index_text(name: &str, text: &str) -> Result<(String, String), String> {
    let entry = parse_entry(name, text)?;
    let derived_title = heading(&entry.body).map(|h| match h.split_once(": ") {
        Some((head, rest)) if head.starts_with("ADR ") => rest.to_string(),
        _ => h.to_string(),
    });
    let status = entry
        .body
        .lines()
        .find_map(|l| l.strip_prefix("- **Status:** "))
        .map(short_status)
        .ok_or_else(|| format!("{name}: no `- **Status:** ...` line (the index shows its first clause)"))?;
    let title = entry.get("title").map(str::to_string).or(derived_title).ok_or_else(|| format!("{name}: no `# ADR NNNN: title` heading"))?;
    Ok((title, status))
}

/// The ADR table, by number.
pub fn adr_block(files: &[(String, String)]) -> Result<Vec<String>, String> {
    let mut rows = Vec::new();
    let mut problems = Vec::new();
    for (name, text) in files {
        let number = match name.split_once('-') {
            Some((n, _)) if n.len() == 4 && n.chars().all(|c| c.is_ascii_digit()) => n.to_string(),
            _ => continue,
        };
        match adr_index_text(name, text) {
            Ok((title, status)) => rows.push((number.clone(), format!("| [{number}]({name}) | {title} | {status} |"))),
            Err(e) => problems.push(e),
        }
    }
    if !problems.is_empty() {
        return Err(problems.join("\n"));
    }
    rows.sort();
    let mut out: Vec<String> = ADR_HEADER.iter().map(|s| s.to_string()).collect();
    out.extend(rows.into_iter().map(|r| r.1));
    Ok(out)
}

/// The title an escape's list line shows: the block's override, else its `#` heading.
pub fn escape_title(name: &str, text: &str) -> Result<String, String> {
    let entry = parse_entry(name, text)?;
    entry.get("title").map(str::to_string).or_else(|| heading(&entry.body).map(str::to_string)).ok_or_else(|| format!("{name}: no `# title` heading"))
}

/// The escapes list: legacy files first in natural order, then the rest by natural id.
pub fn escapes_block(files: &[(String, String)]) -> Result<Vec<String>, String> {
    let mut rows = Vec::new();
    let mut problems = Vec::new();
    for (name, text) in files {
        let stem = name.trim_end_matches(".md");
        let legacy = is_legacy(stem);
        if !legacy && let Err(e) = id_rule(stem) {
            problems.push(e);
            continue;
        }
        match escape_title(name, text) {
            Ok(title) => rows.push(((u8::from(!legacy), natural_key(name)), format!("- [{title}]({name})"))),
            Err(e) => problems.push(e),
        }
    }
    if !problems.is_empty() {
        return Err(problems.join("\n"));
    }
    rows.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(rows.into_iter().map(|r| r.1).collect())
}

/// Ids are unique across the known issues and the escapes (a citation is the folder plus the id).
pub fn unique_ids(known: &[(String, String)], escapes: &[(String, String)]) -> Result<(), String> {
    let mut seen: BTreeMap<String, String> = BTreeMap::new();
    let mut problems = Vec::new();
    let ids = known
        .iter()
        .map(|(n, _)| (n.trim_end_matches(".md").to_string(), format!("known-issues/entries/{n}")))
        .chain(escapes.iter().map(|(n, _)| (escape_id(n.trim_end_matches(".md")), format!("escapes/{n}"))));
    for (id, file) in ids {
        if let Some(first) = seen.insert(id.to_lowercase(), file.clone()) {
            problems.push(format!("the id `{id}` is used by both {first} and {file}; a second entry on the same issue is named `issue-<n>-b`"));
        }
    }
    if problems.is_empty() { Ok(()) } else { Err(problems.join("\n")) }
}

/// `readme` with the text between the markers replaced by `block`.
pub fn splice(readme: &str, block: &[String]) -> Result<String, String> {
    let readme = normalize(readme);
    let begin = readme.find(BEGIN).ok_or("README lacks the indexes:begin marker")?;
    let end = readme.find(END).ok_or("README lacks the indexes:end marker")?;
    if end < begin {
        return Err("README has the indexes markers in the wrong order".into());
    }
    let mut out = String::from(&readme[..begin + BEGIN.len()]);
    out.push('\n');
    for line in block {
        out.push_str(line);
        out.push('\n');
    }
    out.push_str(&readme[end..]);
    Ok(out)
}

fn kinds(root: &Path) -> Result<Vec<(String, Vec<String>)>, String> {
    let known = md_files(&root.join(KNOWN_ENTRIES))?;
    let adrs = md_files(&root.join(ADR_DIR))?;
    let escapes = md_files(&root.join(ESCAPES_DIR))?;
    let mut problems = Vec::new();
    let mut take = |r: Result<Vec<String>, String>| r.map_err(|e| problems.push(e)).unwrap_or_default();
    let blocks = vec![
        (KNOWN_README.to_string(), take(known_block(&known))),
        (format!("{ADR_DIR}/README.md"), take(adr_block(&adrs))),
        (format!("{ESCAPES_DIR}/README.md"), take(escapes_block(&escapes))),
    ];
    if let Err(e) = unique_ids(&known, &escapes) {
        problems.push(e);
    }
    if problems.is_empty() { Ok(blocks) } else { Err(problems.join("\n")) }
}

/// For each README: its path, its current text and the text it should have (both with LF line ends).
pub fn generate(root: &Path) -> Result<Vec<(PathBuf, String, String)>, String> {
    let mut out = Vec::new();
    for (readme, block) in kinds(root)? {
        let path = root.join(&readme);
        let old = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let new = splice(&old, &block).map_err(|e| format!("{readme}: {e}"))?;
        out.push((path, normalize(&old), new));
    }
    Ok(out)
}

/// `--validate`: the entry files parse and follow the id and link rules; no README is read or written.
pub fn run_validate(root: &Path) -> Result<(), String> {
    kinds(root)?;
    check_links(root)?;
    println!("indexes: entries ok");
    Ok(())
}

/// `check` is the drift gate: it writes nothing and names the READMEs that differ. Without it the READMEs are
/// rewritten; a second run changes nothing.
pub fn run_generate(root: &Path, check: bool) -> Result<(), String> {
    let mut stale = Vec::new();
    for (path, old, new) in generate(root)? {
        if old != new {
            let rel = path.strip_prefix(root).unwrap_or(&path).display().to_string().replace('\\', "/");
            if !check {
                fs::write(&path, &new).map_err(|e| format!("{rel}: {e}"))?;
            }
            stale.push(rel);
        }
    }
    if check && !stale.is_empty() {
        return Err(format!("the generated index is out of date in: {}\nrun `cargo xtask indexes` and commit the result", stale.join(", ")));
    }
    println!("indexes: {}", if stale.is_empty() { "ok (current)".to_string() } else { format!("rewrote {}", stale.join(", ")) });
    Ok(())
}

// ---- the one-shot converter (`--split-legacy`) ----

/// The lines of the table or list region of an old README: `(first line index, one past the last)`.
fn region(lines: &[&str], start: impl Fn(&str) -> bool, member: impl Fn(&str) -> bool) -> Result<(usize, usize), String> {
    let first = lines.iter().position(|l| start(l)).ok_or("no table or list found")?;
    let mut last = first;
    while last < lines.len() && member(lines[last]) {
        last += 1;
    }
    Ok((first, last))
}

fn cells(row: &str) -> Result<Vec<String>, String> {
    // One legacy row (K59) lacks its closing pipe; the generator always writes it.
    let inner = row.strip_prefix("| ").ok_or_else(|| format!("not a table row: {row}"))?;
    let inner = inner.strip_suffix(" |").unwrap_or(inner);
    if inner.contains(META_CLOSE) {
        return Err(format!("a cell contains `-->`, which would end the index block: {row}"));
    }
    Ok(inner.split(" | ").map(str::to_string).collect())
}

fn link(text: &str) -> Result<(&str, &str), String> {
    let bad = || format!("not a link: {text}");
    let rest = text.strip_prefix('[').ok_or_else(bad)?;
    let mid = rest.find("](").ok_or_else(bad)?;
    let target = rest[mid + 2..].strip_suffix(')').ok_or_else(bad)?;
    Ok((&rest[..mid], target))
}

fn read_lf(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map(|t| normalize(&t)).map_err(|e| format!("{}: {e}", path.display()))
}

/// Writes the entry files from the three hand-edited tables and replaces each table with its markers, then
/// generates. Every cell is kept verbatim (links rebased to the entry's folder): an ADR or escape gets an index
/// block only where the legacy text differs from what its heading and status line give. Refuses a README that
/// already has markers.
pub fn split_legacy(root: &Path) -> Result<(), String> {
    // Known issues: one file per row, the id the file name, the historical position in `order`.
    let readme = root.join(KNOWN_README);
    let text = read_lf(&readme)?;
    if text.contains(BEGIN) {
        return Err(format!("{KNOWN_README} already has the markers; nothing to split"));
    }
    let lines: Vec<&str> = text.lines().collect();
    let (first, last) = region(&lines, |l| l == KNOWN_HEADER[0], |l| l.starts_with('|'))?;
    fs::create_dir_all(root.join(KNOWN_ENTRIES)).map_err(|e| e.to_string())?;
    for (n, row) in lines[first + 2..last].iter().enumerate() {
        let c: Vec<String> = cells(row)?.iter().map(|cell| map_links(cell, &to_entry_target)).collect();
        if c.len() < 3 || c.len() > 4 {
            return Err(format!("known-issues row {} has {} cells: {row}", n + 1, c.len()));
        }
        let order = (n + 1).to_string();
        let mut fields = vec![("status", c[2].as_str())];
        if let Some(f) = c.get(3) {
            fields.push(("follow-up", f.as_str()));
        }
        fields.push(("order", order.as_str()));
        let path = root.join(KNOWN_ENTRIES).join(format!("{}.md", c[0]));
        fs::write(path, render_entry(&fields, &c[1])).map_err(|e| e.to_string())?;
    }
    write_markers(&readme, &lines, first, last)?;

    // ADRs.
    let readme = root.join(ADR_DIR).join("README.md");
    let text = read_lf(&readme)?;
    let lines: Vec<&str> = text.lines().collect();
    let (first, last) = region(&lines, |l| l == ADR_HEADER[0], |l| l.starts_with('|'))?;
    for row in &lines[first + 2..last] {
        let c = cells(row)?;
        if c.len() != 3 {
            return Err(format!("ADR row has {} cells: {row}", c.len()));
        }
        let (_, file) = link(&c[0])?;
        let path = root.join(ADR_DIR).join(file);
        let original = read_lf(&path)?;
        let (title, _) = adr_index_text(file, &original)?;
        if title != c[1] {
            fs::write(&path, render_entry(&[("title", c[1].as_str())], "") + &original).map_err(|e| format!("{}: {e}", path.display()))?;
        }
    }
    write_markers(&readme, &lines, first, last)?;

    // Escapes.
    let readme = root.join(ESCAPES_DIR).join("README.md");
    let text = read_lf(&readme)?;
    let lines: Vec<&str> = text.lines().collect();
    let (first, last) = region(&lines, |l| l.starts_with("- ["), |l| l.starts_with("- ["))?;
    for line in &lines[first..last] {
        let (title, file) = link(&line[2..])?;
        let path = root.join(ESCAPES_DIR).join(file);
        let original = read_lf(&path)?;
        if escape_title(file, &original)? != title {
            fs::write(&path, render_entry(&[("title", title)], "") + &original).map_err(|e| format!("{}: {e}", path.display()))?;
        }
    }
    write_markers(&readme, &lines, first, last)?;
    run_generate(root, false)
}

fn write_markers(readme: &Path, lines: &[&str], first: usize, last: usize) -> Result<(), String> {
    let mut out: Vec<&str> = lines[..first].to_vec();
    out.extend([BEGIN, END]);
    out.extend(&lines[last..]);
    fs::write(readme, out.join("\n") + "\n").map_err(|e| format!("{}: {e}", readme.display()))
}

pub fn run(root: &Path, args: &[String]) -> Result<(), String> {
    match args.iter().map(String::as_str).collect::<Vec<_>>().as_slice() {
        [] => {
            check_links(root)?;
            run_generate(root, false)
        }
        ["--validate"] => run_validate(root),
        ["--check"] => {
            check_links(root)?;
            run_generate(root, true)
        }
        ["--split-legacy"] => split_legacy(root),
        _ => Err("usage: cargo xtask indexes [--validate | --check | --split-legacy]".into()),
    }
}

